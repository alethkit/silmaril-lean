#!/usr/bin/env python3
"""The C => C translation fixture: run the Lean probe on the translations' C text and write the
trusted stages' exact outputs and the Lean module that quotes them.

    python3 -I tools/compiler-explorer/c2c.py      # needs `lake` (the probe runs in Lean)

Writes examples/compiler-explorer/c2c/core-probe.txt (the probe's output: typed Ail, then the
Core document) and examples/compiles-to/CompilesToExamples/Explorer/C2C/Defs.lean (the C text,
the quoted typed Ail, checked against the frontend by `#guard`, the quoted Core and one `CFn` per
function). The proofs are written by hand next to it.
"""
import os
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "examples" / "compiler-explorer" / "c2c" / "translations.c"
PROBE_OUT = SRC.with_name("core-probe.txt")
MODULE = ROOT / "examples" / "compiles-to" / "CompilesToExamples" / "Explorer" / "C2C" / "Defs.lean"
FUNCTIONS = ["add3_reassoc", "add3_op", "add3_double", "add3_operand", "add3_drop"]


def lean_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(p.capitalize() for p in rest)


def probe(text: str) -> str:
    with tempfile.TemporaryDirectory() as tmp:
        f = pathlib.Path(tmp) / "Probe.lean"
        f.write_text("import Silmaril.Project.CompilesTo.Probe.Defs\n\nopen Lean Elab Command in\n"
                     f'run_cmd logWarning m!"{{Silmaril.Project.CompilesTo.Probe.docText {lean_string(text)}}}"\n')
        out = subprocess.run([os.environ.get("LAKE", "lake"), "env", "lean", str(f)], cwd=ROOT,
                             capture_output=True, text=True, timeout=900)
    s = out.stdout + out.stderr
    i = s.index("BEGIN-TYPED-AIL")
    j = s.index("END-CORE-DOCUMENT") + len("END-CORE-DOCUMENT")
    return s[i:j] + "\n"


def main() -> int:
    text = SRC.read_text()
    raw = probe(text)
    PROBE_OUT.write_text(raw)
    ail = re.search(r"BEGIN-TYPED-AIL\n(.*)\nEND-TYPED-AIL", raw, re.S).group(1)
    doc = re.search(r"BEGIN-CORE-DOCUMENT\n(.*)END-CORE-DOCUMENT", raw, re.S).group(1)
    fns = "\n".join(
        f"/-- `{f}` as Cerberus Core. -/\n"
        f"def {camel(f)}Fn : CFn ⟨[.int32, .int32, .int32], some .int32⟩ where\n"
        f"  file := core.toFile\n  params := paramsOf core \"{f}\"\n  body := (procParts core \"{f}\").2\n"
        for f in FUNCTIONS)
    MODULE.write_text(f'''module

-- GENERATED by tools/compiler-explorer/c2c.py from examples/compiler-explorer/c2c/translations.c.

public import Silmaril.Project.Shapes.CompilesTo.Defs
public import Silmaril.Cerberus.Core.Quote.Defs
public import Silmaril.Cerberus.Ail.Quote.Defs
public meta import Silmaril.Project.CompilesTo.Probe.Defs

/-!
# C => C translations of `add3`: the C text, its typed Ail and its Core

The trusted stages of `examples/compiler-explorer/c2c/translations.c`, exactly as the explorer
shows them: the frontend's typed Ail (quoted; checked against the frontend by `#guard`, compiled
evaluation, because its typing pass is `partial`) and the elaborator's Core document (quoted, the
probe's output `core-probe.txt`). Each function is a `CFn` of that Core.
-/

namespace CompilesToExamples.Explorer.C2C

open Silmaril.Project.CompilesTo
open Silmaril.Project.Shapes.CompilesTo
open Silmaril.Project.Shapes.C (CFn ElaboratesTo FrontendAil)

@[expose] public section

/-- The C source, verbatim. -/
def cText : String :=
  {lean_string(text)}

set_option maxRecDepth 100000 in
/-- Its typed Ail (the Lean Cerberus frontend's output, quoted). -/
def ail : Silmaril.Cerberus.Ail.TypedProgram := ail_program% {lean_string(ail)}

-- C → typed Ail: the frontend, by compiled evaluation, gives exactly the quoted `ail`.
#guard (FrontendAil cText).toOption.map Silmaril.Project.CompilesTo.Probe.ailText ==
  some (Silmaril.Project.CompilesTo.Probe.ailText ail)

set_option maxRecDepth 100000 in
/-- Its Cerberus Core (`ElabAil ail`), quoted from the probe's document. -/
def doc : Silmaril.Cerberus.Codec.Document := core_document% {lean_string(doc)}

/-- The quoted Core with the return labels named as the elaborator names them. -/
def core : Silmaril.Cerberus.Codec.FileBindings := fixRet doc.bindings

{fns}
end

end CompilesToExamples.Explorer.C2C
''')
    print(f"wrote {PROBE_OUT.relative_to(ROOT)} and {MODULE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
